import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const pluginsDir = path.resolve(rootDir, 'plugins');
const generatedDir = path.resolve(rootDir, 'src/generated');
const targetRegistryFile = path.resolve(generatedDir, 'plugin-registry.ts');

const CURRENT_SDK_VERSION = '1.0.0';

interface ValidatedPlugin {
  id: string;
  variableName: string;
  name: string;
  version: string;
  description: string;
  author: string;
  entryPath: string; // Relative to src/generated
  manifestPath: string;
  sdkVersion: string;
  enabledByDefault: boolean;
}

function sanitizeIdentifier(name: string): string {
  return name.replace(/[^a-zA-Z0-9_]/g, '_').replace(/^([0-9])/, '_$1');
}

function checkSdkVersionCompatibility(pluginSdkVersion?: string): boolean {
  if (!pluginSdkVersion) return true; // Loose compatibility if not specified
  const clean = pluginSdkVersion.replace(/[\^~>=<]/g, '').trim();
  const major = clean.split('.')[0];
  return major === '1' || major === '0';
}

export function generatePluginRegistry(): { total: number; valid: number; errors: string[] } {
  console.log('[RegistryGenerator] Scanning plugins directory...');

  if (!fs.existsSync(pluginsDir)) {
    fs.mkdirSync(pluginsDir, { recursive: true });
  }
  if (!fs.existsSync(generatedDir)) {
    fs.mkdirSync(generatedDir, { recursive: true });
  }

  const entries = fs.readdirSync(pluginsDir, { withFileTypes: true });
  const validatedPlugins: ValidatedPlugin[] = [];
  const errors: string[] = [];

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const pluginFolder = path.join(pluginsDir, entry.name);

    // Find manifest
    let manifestData: any = null;
    let manifestFilePath = '';
    const manifestCandidates = ['plugin.json', 'plugin-manifest.json', 'package.json'];

    for (const c of manifestCandidates) {
      const p = path.join(pluginFolder, c);
      if (fs.existsSync(p)) {
        try {
          manifestData = JSON.parse(fs.readFileSync(p, 'utf-8'));
          manifestFilePath = p;
          break;
        } catch (e: any) {
          errors.push(`Plugin "${entry.name}": Corrupted JSON in ${c} (${e.message})`);
        }
      }
    }

    if (!manifestData) {
      console.warn(`[RegistryGenerator] Skipping "${entry.name}": No manifest found.`);
      continue;
    }

    const pluginId = manifestData.id || manifestData.name || entry.name;
    const pluginName = manifestData.name || entry.name;
    const pluginVersion = manifestData.version || '1.0.0';
    const sdkVersion = manifestData.sdkVersion || '^1.0.0';

    // Validate SDK Compatibility
    if (!checkSdkVersionCompatibility(sdkVersion)) {
      const msg = `Plugin "${pluginId}" requires SDK version "${sdkVersion}", incompatible with current SDK v${CURRENT_SDK_VERSION}`;
      errors.push(msg);
      console.error(`[RegistryGenerator] ${msg}`);
      continue;
    }

    // Determine Entry File - MUST be in frontend folder or explicit frontend field
    const entryCandidates = [
      manifestData.frontend ? path.join(pluginFolder, manifestData.frontend) : null,
      path.join(pluginFolder, 'frontend/index.ts'),
      path.join(pluginFolder, 'frontend/index.js'),
      path.join(pluginFolder, 'frontend/src/index.ts'),
    ].filter(Boolean) as string[];

    let resolvedEntry: string | null = null;
    for (const ec of entryCandidates) {
      if (fs.existsSync(ec)) {
        resolvedEntry = ec;
        break;
      }
    }

    if (!resolvedEntry) {
      console.warn(`[RegistryGenerator] Plugin "${pluginId}" has no valid frontend entry (e.g. frontend/index.ts). Skipped.`);
      continue;
    }

    // Calculate relative path from src/generated to entry file
    let relativeImport = path.relative(generatedDir, resolvedEntry).replace(/\\/g, '/');
    if (!relativeImport.startsWith('.')) {
      relativeImport = './' + relativeImport;
    }
    // Remove .ts extension for ESM import
    relativeImport = relativeImport.replace(/\.ts$/, '');

    const varName = sanitizeIdentifier(`plugin_${pluginId}`);

    validatedPlugins.push({
      id: pluginId,
      variableName: varName,
      name: pluginName,
      version: pluginVersion,
      description: manifestData.description || '',
      author: manifestData.author || 'Universal Platform',
      entryPath: relativeImport,
      manifestPath: manifestFilePath,
      sdkVersion,
      enabledByDefault: manifestData.enabledByDefault !== false,
    });
  }

  // Generate the TypeScript registry file
  const fileLines: string[] = [
    '/**',
    ' * AUTOGENERATED FILE - DO NOT EDIT MANUALLY',
    ' * Generated by scripts/generate-plugin-registry.ts at build time',
    ` * Generated on: ${new Date().toISOString()}`,
    ` * Target SDK Version: ${CURRENT_SDK_VERSION}`,
    ' */',
    '',
    "import type { FrontendPluginDefinition } from '@itest/frontend-sdk';",
    '',
  ];

  if (validatedPlugins.length === 0) {
    fileLines.push('// No external plugins registered at build time');
  } else {
    for (const p of validatedPlugins) {
      fileLines.push(`// Plugin: ${p.name} (${p.id}) v${p.version}`);
      fileLines.push(`import * as ${p.variableName}_module from '${p.entryPath}';`);
    }
  }

  fileLines.push('');
  fileLines.push('export interface RegisteredPluginEntry {');
  fileLines.push('  id: string;');
  fileLines.push('  name: string;');
  fileLines.push('  version: string;');
  fileLines.push('  description: string;');
  fileLines.push('  author: string;');
  fileLines.push('  sdkVersion: string;');
  fileLines.push('  plugin: FrontendPluginDefinition;');
  fileLines.push('  enabledByDefault: boolean;');
  fileLines.push('}');
  fileLines.push('');
  fileLines.push('export const buildTimePlugins: RegisteredPluginEntry[] = [');

  for (const p of validatedPlugins) {
    fileLines.push('  {');
    fileLines.push(`    id: ${JSON.stringify(p.id)},`);
    fileLines.push(`    name: ${JSON.stringify(p.name)},`);
    fileLines.push(`    version: ${JSON.stringify(p.version)},`);
    fileLines.push(`    description: ${JSON.stringify(p.description)},`);
    fileLines.push(`    author: ${JSON.stringify(p.author)},`);
    fileLines.push(`    sdkVersion: ${JSON.stringify(p.sdkVersion)},`);
    fileLines.push(`    plugin: ((${p.variableName}_module as any).default || Object.values(${p.variableName}_module)[0]) as FrontendPluginDefinition,`);
    fileLines.push(`    enabledByDefault: ${p.enabledByDefault},`);
    fileLines.push('  },');
  }

  fileLines.push('];');
  fileLines.push('');
  fileLines.push('export const registryDiagnostics = {');
  fileLines.push(`  totalPlugins: ${validatedPlugins.length},`);
  fileLines.push(`  generatedAt: ${JSON.stringify(new Date().toISOString())},`);
  fileLines.push(`  sdkVersion: ${JSON.stringify(CURRENT_SDK_VERSION)},`);
  fileLines.push('};');
  fileLines.push('');

  fs.writeFileSync(targetRegistryFile, fileLines.join('\n'), 'utf-8');
  console.log(`[RegistryGenerator] Successfully generated ${targetRegistryFile} with ${validatedPlugins.length} frontend plugin(s).`);

  return {
    total: entries.length,
    valid: validatedPlugins.length,
    errors,
  };
}

if (process.argv[1] && process.argv[1].endsWith('generate-plugin-registry.ts')) {
  generatePluginRegistry();
}
